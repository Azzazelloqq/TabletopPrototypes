// Bitmap fonts (5x7 small, 6x9 big digits, 3x5 tiny digits) and canvas helpers. 1 texel = 1 canvas pixel.

export function makeCanvas(w, h) {
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  canvas.getContext('2d').imageSmoothingEnabled = false;
  return canvas;
}

// Builds a sprite from text rows; key maps a character to a colour, unknown characters stay transparent.
export function spriteFromRows(rows, key) {
  const w = Math.max(...rows.map(row => row.length));
  const canvas = makeCanvas(w, rows.length);
  const g = canvas.getContext('2d');
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const colour = key[row[x]];
      if (!colour) continue;
      g.fillStyle = colour;
      g.fillRect(x, y, 1, 1);
    }
  });
  return canvas;
}

