const glyphCache = new Map();
function glyphSprite(font, ch, colour) {
  const key = `${font.name}|${ch}|${colour}`;
  let sprite = glyphCache.get(key);
  if (!sprite) {
    sprite = spriteFromRows(font.glyphs[ch] ?? font.glyphs['?'] ?? font.glyphs[' '], { '#': colour });
    glyphCache.set(key, sprite);
  }
  return sprite;
}

const glyphWidth = (font, ch) => (font.glyphs[ch] ?? font.glyphs['?'] ?? font.glyphs[' '])[0].length;

export function textWidth(text, font = SMALL) {
  let w = 0;
  for (const ch of text) w += glyphWidth(font, ch) + font.spacing;
  return Math.max(0, w - font.spacing);
}

// opts: { font, align: 'left' | 'center' | 'right', shadow: colour, scale: whole number }
export function drawText(ctx, text, x, y, colour, opts = {}) {
  const font = opts.font ?? SMALL;
  const s = opts.scale ?? 1;
  if (opts.align === 'center') x -= Math.floor(textWidth(text, font) * s / 2);
  else if (opts.align === 'right') x -= textWidth(text, font) * s;
  x = Math.round(x);
  y = Math.round(y);
  for (const ch of text) {
    if (opts.shadow) drawGlyph(ctx, font, ch, opts.shadow, x + s, y + s, s);
    drawGlyph(ctx, font, ch, colour, x, y, s);
    x += (glyphWidth(font, ch) + font.spacing) * s;
  }
}

function drawGlyph(ctx, font, ch, colour, x, y, s) {
  const sprite = glyphSprite(font, ch, colour);
  if (s === 1) ctx.drawImage(sprite, x, y);
  else ctx.drawImage(sprite, x, y, sprite.width * s, sprite.height * s);
}

