export const GLYPHS = {};
for (const [ch, src] of Object.entries(G)) {
  const rows = src.split('|');
  GLYPHS[ch] = { rows, w: rows[0].length };
}

export const LINE_HEIGHT = 10;
const SPACE = 3;

export function textWidth(text, scale = 1) {
  let w = 0;
  for (const ch of text) w += (ch === ' ' ? SPACE : (GLYPHS[ch] ? GLYPHS[ch].w : 3)) + 1;
  return Math.max(0, w - 1) * scale;
}

// Plots glyph pixels via fillRect; callers cache the result (see art.js text()).
export function plotText(ctx, text, x, y, scale = 1) {
  for (const ch of text) {
    const g = GLYPHS[ch];
    if (ch === ' ' || !g) { x += (SPACE + 1) * scale; continue; }
    g.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) {
        if (row[rx] === '#') ctx.fillRect(x + rx * scale, y + ry * scale, scale, scale);
      }
    });
    x += (g.w + 1) * scale;
  }
}

// Greedy word wrap to a pixel width.
export function wrap(text, maxWidth, scale = 1) {
  const lines = [];
  let line = '';
  for (const word of text.split(' ')) {
    const next = line ? line + ' ' + word : word;
    if (line && textWidth(next, scale) > maxWidth) { lines.push(line); line = word; }
    else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
